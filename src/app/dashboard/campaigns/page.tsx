'use client';

import React, { useEffect, useState } from 'react';
import Link from 'next/link';
import { Target, Play, Pause, Sparkles, ArrowLeft, BrainCircuit, ShieldAlert, TrendingUp, Users, DollarSign } from 'lucide-react';
import { store } from '@/lib/db/store';
import { formatINR, formatDate } from '@/lib/utils';
import { Campaign } from '@/types';

export default function CampaignsDashboardPage() {
  const [campaigns, setCampaigns] = useState<Campaign[]>(store.getCampaigns());

  useEffect(() => {
    const unsub = store.subscribe(() => {
      setCampaigns(store.getCampaigns());
    });
    return unsub;
  }, []);

  const handleToggleStatus = (id: string, currentStatus: Campaign['status']) => {
    const nextStatus = currentStatus === 'active' ? 'paused' : 'active';
    store.updateCampaignStatus(id, nextStatus);
  };

  const activeCount = campaigns.filter((c) => c.status === 'active').length;
  const totalRealizedRev = campaigns.reduce((sum, c) => sum + c.realizedRevenue, 0);
  const totalAudience = campaigns.reduce((sum, c) => sum + c.audienceSize, 0);
  const avgConfidence = campaigns.length > 0
    ? Math.round(campaigns.reduce((sum, c) => sum + c.aiConfidence, 0) / campaigns.length)
    : 90;

  const getResponsibleAgent = (cmpName: string) => {
    if (cmpName.toLowerCase().includes('recovery')) {
      return { name: 'Revenue Recovery Agent', icon: ShieldAlert, color: 'text-amber-700 bg-amber-50 dark:bg-amber-950/40 border-amber-200' };
    }
    if (cmpName.toLowerCase().includes('bundle') || cmpName.toLowerCase().includes('upsell')) {
      return { name: 'Revenue Growth Agent', icon: TrendingUp, color: 'text-teal-700 bg-teal-50 dark:bg-teal-950/40 border-teal-200' };
    }
    return { name: 'Commerce Recommendation Agent', icon: BrainCircuit, color: 'text-indigo-700 bg-indigo-50 dark:bg-indigo-950/40 border-indigo-200' };
  };

  return (
    <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-6 space-y-8 font-sans pb-16">
      {/* Back Link & Header */}
      <div className="flex flex-col md:flex-row md:items-center justify-between gap-4 border-b border-zinc-200/80 dark:border-zinc-800 pb-5">
        <div className="space-y-1">
          <Link
            href="/"
            className="inline-flex items-center gap-1.5 text-xs font-bold text-zinc-500 hover:text-zinc-900 transition-colors mb-1 group"
          >
            <ArrowLeft className="w-3.5 h-3.5 group-hover:-translate-x-0.5 transition-transform text-teal-600" />
            <span>Back to ANTARA</span>
          </Link>
          <div className="flex items-center gap-2 text-xs font-semibold text-teal-700 dark:text-teal-400">
            <Target className="w-4 h-4 text-teal-600" />
            <span>Autonomous Revenue Interventions</span>
          </div>
          <h1 className="text-2xl font-black text-zinc-900 dark:text-zinc-100 tracking-tight">
            AI Growth Campaigns
          </h1>
          <p className="text-xs text-zinc-500 max-w-2xl leading-relaxed">
            Autonomous campaigns designed to increase conversion, recover lost revenue, and grow average order value.
          </p>
        </div>
      </div>

      {/* Top Metrics Summary Grid */}
      <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-4">
        <div className="p-5 rounded-2xl bg-white dark:bg-zinc-900 border border-zinc-200/80 dark:border-zinc-800 shadow-subtle">
          <div className="flex items-center justify-between text-zinc-500">
            <span className="text-xs font-bold uppercase tracking-wider">Active Campaigns</span>
            <Target className="w-4 h-4 text-teal-600" />
          </div>
          <div className="mt-3">
            <span className="text-2xl font-extrabold text-zinc-900 dark:text-zinc-100 block">
              {activeCount} / {campaigns.length}
            </span>
            <span className="text-[11px] font-semibold text-emerald-600 mt-1 block">
              ● All Agents Operational
            </span>
          </div>
        </div>

        <div className="p-5 rounded-2xl bg-white dark:bg-zinc-900 border border-teal-500/30 shadow-subtle">
          <div className="flex items-center justify-between text-teal-700 dark:text-teal-400">
            <span className="text-xs font-bold uppercase tracking-wider">Realized Revenue</span>
            <Sparkles className="w-4 h-4 text-teal-600" />
          </div>
          <div className="mt-3">
            <span className="text-2xl font-black text-teal-950 dark:text-teal-100 block">
              {formatINR(totalRealizedRev)}
            </span>
            <span className="text-[11px] font-mono text-teal-700 dark:text-teal-300 mt-1 block">
              Directly Generated by AI
            </span>
          </div>
        </div>

        <div className="p-5 rounded-2xl bg-white dark:bg-zinc-900 border border-zinc-200/80 dark:border-zinc-800 shadow-subtle">
          <div className="flex items-center justify-between text-zinc-500">
            <span className="text-xs font-bold uppercase tracking-wider">Target Audience</span>
            <Users className="w-4 h-4 text-zinc-400" />
          </div>
          <div className="mt-3">
            <span className="text-2xl font-extrabold text-zinc-900 dark:text-zinc-100 block">
              {totalAudience} shoppers
            </span>
            <span className="text-[11px] font-semibold text-zinc-500 mt-1 block">
              Behavioral Segments Reached
            </span>
          </div>
        </div>

        <div className="p-5 rounded-2xl bg-white dark:bg-zinc-900 border border-zinc-200/80 dark:border-zinc-800 shadow-subtle">
          <div className="flex items-center justify-between text-zinc-500">
            <span className="text-xs font-bold uppercase tracking-wider">Avg AI Confidence</span>
            <BrainCircuit className="w-4 h-4 text-teal-600" />
          </div>
          <div className="mt-3">
            <span className="text-2xl font-extrabold text-teal-600 block">
              {avgConfidence}%
            </span>
            <span className="text-[11px] font-semibold text-zinc-500 mt-1 block">
              Decision Precision Benchmark
            </span>
          </div>
        </div>
      </div>

      {/* Campaign Cards Grid */}
      <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
        {campaigns.map((cmp) => {
          const agent = getResponsibleAgent(cmp.name);
          const AgentIcon = agent.icon;

          return (
            <div
              key={cmp.id}
              className="p-6 rounded-2xl bg-white dark:bg-zinc-900 border border-zinc-200/80 dark:border-zinc-800 shadow-subtle flex flex-col justify-between hover:border-zinc-300 transition-all"
            >
              <div>
                <div className="flex items-center justify-between mb-3 gap-2 flex-wrap">
                  <span className={`text-[10px] font-bold uppercase tracking-wider font-mono px-2.5 py-0.5 rounded border flex items-center gap-1 ${agent.color}`}>
                    <AgentIcon className="w-3 h-3" />
                    {agent.name}
                  </span>

                  <span
                    className={`text-xs font-bold px-2.5 py-0.5 rounded-full flex items-center gap-1 ${
                      cmp.status === 'active'
                        ? 'bg-emerald-100 text-emerald-800 dark:bg-emerald-950/60 dark:text-emerald-300'
                        : 'bg-zinc-100 text-zinc-600 dark:bg-zinc-800 dark:text-zinc-400'
                    }`}
                  >
                    <span className={`w-1.5 h-1.5 rounded-full ${cmp.status === 'active' ? 'bg-emerald-500' : 'bg-zinc-400'}`} />
                    {cmp.status.toUpperCase()}
                  </span>
                </div>

                <h3 className="text-base font-extrabold text-zinc-900 dark:text-zinc-100">
                  {cmp.name}
                </h3>
                <p className="text-xs text-zinc-500 mt-1 leading-relaxed">
                  {cmp.description}
                </p>

                {/* Offer Mechanism Badge */}
                <div className="mt-3">
                  <span className="text-[10px] font-mono px-2.5 py-1 rounded bg-zinc-100 dark:bg-zinc-800 text-zinc-600 dark:text-zinc-300 font-semibold border border-zinc-200/60 dark:border-zinc-700">
                    Mechanism: {cmp.offerType}
                  </span>
                </div>

                {/* Performance Metrics Grid */}
                <div className="grid grid-cols-3 gap-3 my-5 p-3.5 rounded-xl bg-zinc-50 dark:bg-zinc-800/40 border border-zinc-200 dark:border-zinc-800">
                  <div>
                    <span className="text-[10px] text-zinc-400 font-bold uppercase block">Target Audience</span>
                    <span className="text-sm font-extrabold text-zinc-900 dark:text-zinc-100 mt-0.5 block">
                      {cmp.audienceSize} shoppers
                    </span>
                  </div>
                  <div>
                    <span className="text-[10px] text-zinc-400 font-bold uppercase block">Potential Rev</span>
                    <span className="text-sm font-extrabold text-teal-600 mt-0.5 block">
                      {formatINR(cmp.expectedRevenue)}
                    </span>
                  </div>
                  <div>
                    <span className="text-[10px] text-zinc-400 font-bold uppercase block">Realized Rev</span>
                    <span className="text-sm font-extrabold text-emerald-600 mt-0.5 block">
                      {formatINR(cmp.realizedRevenue)}
                    </span>
                  </div>
                </div>
              </div>

              {/* Action Footer */}
              <div className="flex items-center justify-between pt-4 border-t border-zinc-100 dark:border-zinc-800 text-xs">
                <span className="text-zinc-500 font-mono">
                  AI Confidence: <strong>{cmp.aiConfidence}%</strong>
                </span>

                <button
                  onClick={() => handleToggleStatus(cmp.id, cmp.status)}
                  className={`px-3.5 py-1.5 rounded-xl font-bold transition-colors flex items-center gap-1.5 shadow-xs ${
                    cmp.status === 'active'
                      ? 'bg-zinc-100 text-zinc-800 hover:bg-zinc-200 dark:bg-zinc-800 dark:text-zinc-200'
                      : 'bg-teal-700 text-white hover:bg-teal-800'
                  }`}
                >
                  {cmp.status === 'active' ? <Pause className="w-3.5 h-3.5" /> : <Play className="w-3.5 h-3.5" />}
                  {cmp.status === 'active' ? 'Pause Campaign' : 'Activate Campaign'}
                </button>
              </div>
            </div>
          );
        })}
      </div>
    </div>
  );
}
